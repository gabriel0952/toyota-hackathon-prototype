import { test, expect } from '@playwright/test'
test('owner questionnaire, consent, advisor update, LINE synchronization and revocation', async ({ page, browser }) => {
  await page.goto('/driver'); await page.getByRole('button',{name:/開始轉電診斷/}).click()
  await page.getByRole('button',{name:/下一步：停車/}).click()
  await page.locator('summary').filter({hasText:'補充停車'}).click()
  await page.getByLabel('住家充電是否已可使用').selectOption('unavailable')
  await page.getByLabel('公司充電是否已可使用').selectOption('unavailable')
  await page.getByLabel('住家安裝評估').selectOption('failed')
  await page.getByLabel('可使用公共充電的時段').selectOption('day')
  await page.getByLabel('住家約略區域').fill('台北市內湖區')
  await page.getByRole('button',{name:/下一步：行程/}).click()
  await page.getByLabel('長途頻率').selectOption('幾乎沒有')
  await page.getByRole('button',{name:/下一步：能源/}).click()
  await page.getByRole('button',{name:/建立我的轉電路徑/}).click()
  await expect(page).toHaveURL(/report\/family-/)
  await expect(page.locator('.decision')).toContainText('公共補電方案可支撐')
  const family = new URL(page.url()).pathname.split('/').pop()!
  const api = page.request
  const original = await (await api.get(`/api/v1/report-families/${family}/latest`)).json()
  await page.getByRole('button',{name:'條件模擬'}).click(); await page.getByRole('button',{name:/模擬家充可用/}).click()
  await expect(page.getByText('模擬 v2')).toBeVisible()
  expect((await (await api.get(`/api/v1/report-families/${family}/latest`)).json()).id).toBe(original.id)
  await page.getByRole('button',{name:'同意分享給示範顧問',exact:true}).click()
  const advisorContext=await browser.newContext(), advisor=await advisorContext.newPage()
  await advisor.goto('/advisor'); await advisor.getByRole('button',{name:'登入本機展示顧問'}).click()
  await expect(advisor.locator('.lead-row').filter({hasText:'RAV4'}).first()).toBeVisible()
  await advisor.goto(`/advisor/reports/${family}`)
  await advisor.getByLabel('已確認住家充電實際可用').check()
  await advisor.getByRole('button',{name:'更新條件並重新評估'}).click()
  await expect(advisor.locator('.decision')).toContainText('穩定補電與行程條件已通過')
  await expect(page.locator('.decision')).toContainText('穩定補電與行程條件已通過',{timeout:12000})
  await advisor.getByLabel('新增紀錄').fill('僅限顧問的測試紀錄'); await advisor.getByRole('button',{name:'儲存紀錄'}).click()
  const latest=await (await api.get(`/api/v1/report-families/${family}/latest`)).json()
  expect(latest).not.toHaveProperty('advisorNotes'); expect(latest.version).toBe(3)
  expect(await (await api.get(`/api/v1/reports/${original.id}`)).json()).toEqual(original)
  await page.getByRole('button',{name:'總覽',exact:true}).click()
  await page.screenshot({path:'artifacts/screenshots/api-driver-v3.png',fullPage:true})
  await advisor.screenshot({path:'artifacts/screenshots/api-advisor-v3.png',fullPage:true})
  await page.goto(`/line/result/${family}`); await expect(page.locator('.line-result-card')).toContainText('v3')
  await page.screenshot({path:'artifacts/screenshots/api-line-v3.png',fullPage:true})
  const stranger=await browser.newContext(); const strangerPage=await stranger.newPage(); await strangerPage.goto(`/driver/report/${family}`)
  await expect(strangerPage.getByRole('alert')).toBeVisible(); await expect(strangerPage.locator('.decision')).toHaveCount(0)
  await page.goto(`/driver/report/${family}`); await page.getByRole('button',{name:'撤銷分享'}).click()
  await expect(advisor.getByRole('alert')).toContainText('分享授權',{timeout:12000})
  await advisorContext.close(); await stranger.close()
})
